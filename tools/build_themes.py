NEON = ("magenta", "violet", "blue", "cyan", "teal", "mint", "amber", "gold", "red")


def css_name(key):
    parts = key.split(".")
    if parts[0] == "color":
        return "--ns-" + parts[1]
    if parts[0] in ("role", "statusline"):
        return "--ns-" + "-".join(parts[1:])
    if parts[0] == "font":
        return "--ns-" + {"family": "font", "weight": "weight", "size": "size", "leading": "leading"}[parts[1]] + "-" + parts[2]
    if parts[0] == "motion":
        return "--ns-" + ("ease" if parts[1] == "ease" else "duration-" + parts[1])
    return "--ns-" + "-".join(parts)


def css_value(key, val, refs):
    if key in refs:
        return "var(%s)" % css_name(refs[key])
    if isinstance(val, list) and key.startswith("font.family"):
        return ", ".join('"%s"' % f if " " in f else f for f in val)
    if isinstance(val, list):
        return "cubic-bezier(%s)" % ", ".join(str(v) for v in val)
    return str(val)


def build_css(tokens, refs):
    out = ["/* %s */" % NOTE, "", ":root {", "  color-scheme: dark;"]
    group = None
    for key, val in tokens.items():
        if key.startswith("glow."):
            continue
        head = key.split(".")[0] if not key.startswith(("role.", "font.")) else ".".join(key.split(".")[:2])
        if head != group:
            out.append("")
            group = head
        out.append("  %s: %s;" % (css_name(key), css_value(key, val, refs)))
    out.append("")
    out.append("  /* rgb triplets, for rgba(var(--ns-rgb-teal), .3) */")
    for key, val in tokens.items():
        if key.startswith("color."):
            out.append("  --ns-rgb-%s: %s;" % (key[6:], "%d, %d, %d" % rgb(val)))
    out.append("")
    out.append("  /* glow: the only elevation */")
    for name in NEON:
        kind = "glow.text" if name in ("magenta", "violet", "blue", "red") else "glow.text-bright"
        out.append("  --ns-glow-%s: %s;" % (name, tokens[kind].replace("{rgb}", "var(--ns-rgb-%s)" % name)))
    for kind in ("button", "tube", "lit", "stage"):
        out.append("  --ns-glow-%s: %s;" % (kind, tokens["glow." + kind].replace("{rgb}", "var(--ns-rgb-magenta)")))
    out.append("}")
    out.append("")
    out.append("@media (prefers-reduced-motion: reduce) {")
    out.append("  :root { --ns-duration-quick: 0ms; --ns-duration-flow: 0ms; }")
    out.append("}")
    put("design/tokens.css", "\n".join(out) + "\n")


