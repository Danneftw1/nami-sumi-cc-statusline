# ── tokens ─────────────────────────────────────────────────────────────────────
def load(path=TOKENS):
    """Flatten the DTCG tree to {"color.magenta": "#ff2ec4", ...} with references resolved."""
    with open(path, encoding="utf-8") as fh:
        raw = json.load(fh)
    flat, refs = {}, {}

    def walk(node, prefix):
        for key, val in node.items():
            if key.startswith("$") or not isinstance(val, dict):
                continue
            if "$value" in val:
                flat[prefix + key] = val["$value"]
            else:
                walk(val, prefix + key + ".")

    walk(raw, "")

    def resolve(key, seen=()):
        val = flat[key]
        m = re.fullmatch(r"\{([^}]+)\}", val) if isinstance(val, str) else None
        if not m:
            return val
        target = m.group(1)
        if target in seen or target not in flat:
            raise SystemExit("tokens.json: bad reference %s -> {%s}" % (key, target))
        refs[key] = target
        return resolve(target, seen + (key,))

    tokens = {k: resolve(k) for k in flat}
    meta = raw.get("$extensions", {}).get("neon-sumi", {})
    return tokens, refs, meta


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexa(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, int(round(v)))) for v in c)


def mix(a, b, t):
    return hexa(tuple(x + (y - x) * t for x, y in zip(rgb(a), rgb(b))))


def put(rel, data):
    """Write a file under ROOT only if its bytes change."""
    path = os.path.join(ROOT, rel)
    data = data.encode("utf-8") if isinstance(data, str) else data
    if os.path.exists(path):
        with open(path, "rb") as fh:
            if fh.read() == data:
                return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(data)
    CHANGED.append(rel)


class Palette:
    """T.magenta -> "#ff2ec4"; T.a("magenta", .2) -> "#ff2ec433"; T["role.text.muted"] -> hex."""

    def __init__(self, tokens):
        self.t = tokens

    def __getattr__(self, name):
        return self.t["color." + name.replace("_", "-")]

    def __getitem__(self, key):
        return self.t[key]

    def a(self, name, alpha):
        base = name if name.startswith("#") else self.t["color." + name.replace("_", "-")]
        return base + "%02x" % int(round(alpha * 255))

    def role(self, path):
        return self.t["role." + path]

    def ansi(self, n):
        return self.t["ansi.%d" % n]


