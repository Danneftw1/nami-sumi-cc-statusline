# ── keep the hand-written ports in step ───────────────────────────────────────
def _retint(rel, anchors, T):
    """anchors: [(regex with one hex group, token key)]. Where a named line in the file holds a colour that
    differs from its token, replace that colour everywhere in the file (hex and r, g, b forms)."""
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        return
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    swaps = {}
    for pattern, key in anchors:
        for m in re.finditer(pattern, text, re.M | re.I):
            old, new = m.group(1).lower(), T[key].lower()
            if old != new:
                swaps[old] = new
    for old, new in swaps.items():
        text = re.sub(re.escape(old), new, text, flags=re.I)
        o, n = rgb(old), rgb(new)
        text = re.sub(r"\b%d,(\s*)%d,(\s*)%d\b" % o, lambda m: "%d,%s%d,%s%d" % (n[0], m.group(1), n[1], m.group(2), n[2]), text)
    if swaps:
        put(rel, text)
        print("  retinted %s: %s" % (rel, ", ".join("%s→%s" % kv for kv in swaps.items())))


